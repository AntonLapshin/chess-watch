// Generate shared/config.generated.js from the root .env (gitignored).
// Validates: non-empty tokens, absolute server URL, no trailing slash.
// Warns when the URL is localhost/127.0.0.1: the watch cannot reach it.
// `make web` also uses this value; override it on the command line to point
// the browser harness at a local relay.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");
const outPath = path.join(root, "shared", "config.generated.js");

function parseEnv(text) {
  const env = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    env[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, "");
  }
  return env;
}

function fail(msg) {
  console.error(`gen-app-config: ${msg}`);
  process.exit(1);
}

let env = { ...process.env };
try {
  env = { ...parseEnv(readFileSync(envPath, "utf8")), ...process.env };
} catch (_) {
  // No .env file: fall back to process environment only.
}

const serverUrl = env.CHESS_SERVER_URL || "";
const p1 = env.CHESS_TOKEN_P1 || "";
const p2 = env.CHESS_TOKEN_P2 || "";
const p1Name = env.CHESS_P1_NAME || "Aurora";
const p2Name = env.CHESS_P2_NAME || "Sam";
const cfAccessId = env.CHESS_CF_ACCESS_CLIENT_ID || "";
const cfAccessSecret = env.CHESS_CF_ACCESS_CLIENT_SECRET || "";

if (!serverUrl) fail("CHESS_SERVER_URL is missing (set it in .env)");
if (!p1) fail("CHESS_TOKEN_P1 is missing (set it in .env)");
if (!p2) fail("CHESS_TOKEN_P2 is missing (set it in .env)");
if (p1 === p2) fail("CHESS_TOKEN_P1 and CHESS_TOKEN_P2 must differ");
if (p1.length < 24) fail("CHESS_TOKEN_P1 must be at least 24 characters");
if (p2.length < 24) fail("CHESS_TOKEN_P2 must be at least 24 characters");
if (p1.startsWith("CHANGEME") || p2.startsWith("CHANGEME")) {
  fail("CHESS_TOKEN_P1/CHESS_TOKEN_P2 are still the .env.example placeholders; generate real tokens");
}
if (Boolean(cfAccessId) !== Boolean(cfAccessSecret)) {
  fail("CHESS_CF_ACCESS_CLIENT_ID and CHESS_CF_ACCESS_CLIENT_SECRET must be set together (or both empty)");
}

let url;
try {
  url = new URL(serverUrl);
} catch (_) {
  fail(`CHESS_SERVER_URL is not an absolute URL: ${serverUrl}`);
}
if (!/^https?:$/.test(url.protocol)) fail(`CHESS_SERVER_URL must be http(s): ${serverUrl}`);
if (serverUrl.endsWith("/")) fail("CHESS_SERVER_URL must not end with a trailing slash");
if (url.hostname === "localhost" || url.hostname === "127.0.0.1") {
  console.warn(
    "gen-app-config: WARNING: CHESS_SERVER_URL is localhost — the watch cannot reach it. " +
    "Use the LAN/VPN or Cloudflare Tunnel address for both the watch and `make web`.",
  );
} else if (url.protocol !== "https:") {
  console.warn(
    "gen-app-config: WARNING: CHESS_SERVER_URL is not https — a watch outside the LAN " +
    "will not reach it reliably. Use the Cloudflare Tunnel hostname for on-device builds.",
  );
}

const access = cfAccessId
  ? { clientId: cfAccessId, clientSecret: cfAccessSecret }
  : null;

const content = `// Generated by scripts/gen-app-config.mjs — DO NOT EDIT, DO NOT COMMIT.
// Contains bearer tokens and (optionally) the Cloudflare Access service token.
// Regenerate after changing .env:
//   npm run config
export default {
  serverUrl: ${JSON.stringify(serverUrl)},
  access: ${JSON.stringify(access)},
  players: {
    p1: { token: ${JSON.stringify(p1)}, name: ${JSON.stringify(p1Name)} },
    p2: { token: ${JSON.stringify(p2)}, name: ${JSON.stringify(p2Name)} },
  },
};
`;
writeFileSync(outPath, content);
console.log(`gen-app-config: wrote ${outPath} (serverUrl=${serverUrl})`);
